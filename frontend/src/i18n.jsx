export function detectLang() {
  try {
    const saved = localStorage.getItem(KEY)
    if (saved && T[saved]) return saved
  } catch { /* private mode */ }
  const nav = (navigator.language || 'fr').slice(0, 2).toLowerCase()
  return T[nav] ? nav : 'fr'
}

// Read by api.js so the backend answers in the same language.
export function currentLang() {
  return detectLang()
}

export function translate(lang, key, vars = {}) {
  const text = (T[lang] && T[lang][key]) ?? T.fr[key] ?? key
  return text.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`))
}

const LangContext = createContext({ lang: 'fr', setLang: () => {}, t: (k) => k })

export function LangProvider({ children }) {
  const [lang, setLangState] = useState(detectLang)
  const value = useMemo(() => ({
    lang,
    setLang: (code) => {
      try { localStorage.setItem(KEY, code) } catch { /* private mode */ }
      document.documentElement.lang = code
      setLangState(code)
    },
    t: (key, vars) => translate(lang, key, vars),
  }), [lang])
  return <LangContext.Provider value={value}>{children}</LangContext.Provider>
}

export function useT() {
  return useContext(LangContext)
}

export function LangSwitch({ className = '' }) {
  const { lang, setLang } = useT()
  return (
    <div className={`inline-flex rounded-full bg-white/90 p-0.5 shadow-card ${className}`} role="group" aria-label="Langue / Language / Idioma">
      {LANGS.map((l) => (
        <button key={l.code} onClick={() => setLang(l.code)} title={l.name} aria-pressed={lang === l.code}
          className={`rounded-full px-2.5 py-1 text-xs font-bold ${lang === l.code ? 'bg-ocean-500 text-white' : 'text-ocean-700'}`}>
          {l.label}
        </button>
      ))}
    </div>
  )
}
